#!/usr/bin/env python3
"""
Seeds the 108-company watchlist (docs/CANDIDATE_UNIVERSE_V1.md) into
entities / entity_aliases / instruments / instrument_identifiers /
watchlist_membership -- Extraction-Runner Design v2, Section 1.

Reads build/seed_data/watchlist_ciks.csv, which was generated by looking up
every watchlist ticker against SEC's own company_tickers.json (and
cross-checked against every CIK's live submissions API record) -- NOT
inferred from memory or training data. Two real discrepancies found during
that lookup are recorded directly in that CSV's `note` column rather than
silently corrected:
  - GPS (Gap Inc.) renamed its ticker to GAP on NYSE; seeded under GAP.
  - XOM (Exxon Mobil) moved to a new CIK in 2026 (holding-company
    reorganization); seeded under the new CIK that now files under the
    XOM ticker.
Both were confirmed against SEC's live submissions API before being
accepted, and both were explicitly decided by the project owner rather
than silently resolved -- see the CSV's note column and the commit history
for this file.

Idempotent: safe to re-run. An entity already seeded (matched by CIK) is
left alone; running this script twice does not create duplicates anywhere.

Known, deliberate limitation: legal_name is taken directly from SEC's own
company title (company_tickers.json), after stripping only the mechanical
"/DE/"-style filing-index suffix some SEC titles carry -- NOT reordered or
"prettied up" from memory (e.g. SEC's own title for D.R. Horton is
"HORTON D R INC /DE/" -- stored, and aliased, as "horton d r" after suffix
stripping, not corrected to "D.R. Horton"). This means a real extraction
that names a company the way its own press releases do (e.g. "D.R.
Horton") could fail to resolve against this seed data alone for the
handful of SEC titles with this kind of ordering quirk. Flagged in the
implementation report as a known gap, not silently worked around with an
unverified guess.
"""

from __future__ import annotations

import argparse
import csv
import logging
import sys
import uuid
from pathlib import Path

import psycopg2

from entity_resolution import normalize_entity_name, strip_sec_filing_index_noise

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
log = logging.getLogger("seed_entities")

DB_DSN = "dbname=diffusion_experiment user=postgres"
CSV_PATH = Path(__file__).parent / "seed_data" / "watchlist_ciks.csv"


def find_entity_by_cik(conn, cik: str) -> str | None:
    with conn.cursor() as cur:
        cur.execute("SELECT entity_id FROM entities WHERE cik = %s", (cik,))
        row = cur.fetchone()
        return row[0] if row else None


def insert_alias(conn, entity_id: str, alias_text: str, alias_source: str) -> None:
    normalized = normalize_entity_name(alias_text)
    if not normalized:
        return
    with conn.cursor() as cur:
        cur.execute(
            """
            INSERT INTO entity_aliases (entity_id, alias_text, normalized_alias, alias_source)
            VALUES (%s, %s, %s, %s)
            ON CONFLICT (entity_id, normalized_alias) DO NOTHING
            """,
            (entity_id, alias_text, normalized, alias_source),
        )


def seed_one(conn, sector: str, watchlist_ticker: str, sec_ticker: str, sec_title: str, cik: str) -> str:
    legal_name = strip_sec_filing_index_noise(sec_title)

    entity_id = find_entity_by_cik(conn, cik)
    if entity_id is None:
        entity_id = str(uuid.uuid4())
        with conn.cursor() as cur:
            cur.execute(
                "INSERT INTO entities (entity_id, legal_name, cik, entity_status) VALUES (%s, %s, %s, 'active')",
                (entity_id, legal_name, cik),
            )
        log.info("Seeded entity %s (%s, CIK %s)", legal_name, watchlist_ticker, cik)
    else:
        log.info("Entity for CIK %s already exists (%s) -- not re-created", cik, legal_name)

    # At minimum: the legal name as written, and the bare name without
    # corporate suffix (design doc §1). normalize_entity_name already
    # strips the suffix, so the "bare name" alias is just the same
    # normalization result stored as its own alias_text too, in case a
    # document names the company without any suffix at all (e.g. just
    # "Nvidia" in prose) -- ON CONFLICT DO NOTHING collapses it with the
    # legal-name alias if they normalize identically anyway.
    insert_alias(conn, entity_id, legal_name, "seed_legal_name")
    bare_name = normalize_entity_name(legal_name)
    if bare_name:
        insert_alias(conn, entity_id, bare_name, "seed_bare_name")

    with conn.cursor() as cur:
        cur.execute("SELECT instrument_id FROM instruments WHERE entity_id = %s", (entity_id,))
        row = cur.fetchone()
        if row:
            instrument_id = row[0]
        else:
            cur.execute(
                "INSERT INTO instruments (entity_id, asset_type) VALUES (%s, 'equity') RETURNING instrument_id",
                (entity_id,),
            )
            instrument_id = cur.fetchone()[0]

        cur.execute(
            "SELECT 1 FROM instrument_identifiers WHERE instrument_id = %s "
            "AND identifier_type = 'ticker' AND identifier_value = %s AND valid_to IS NULL",
            (instrument_id, sec_ticker),
        )
        if not cur.fetchone():
            cur.execute(
                """
                INSERT INTO instrument_identifiers (instrument_id, identifier_type, identifier_value, valid_from)
                VALUES (%s, 'ticker', %s, now())
                """,
                (instrument_id, sec_ticker),
            )

    with conn.cursor() as cur:
        cur.execute(
            "INSERT INTO watchlist_membership (entity_id, cik) VALUES (%s, %s) ON CONFLICT (entity_id) DO NOTHING",
            (entity_id, cik),
        )

    return entity_id


def seed_all(conn, csv_path: Path = CSV_PATH) -> list[tuple[str, str]]:
    """Returns the (cik, entity_id) pairs seeded/confirmed -- the same
    shape edgar_ingest_worker.py's WATCHLIST used to be hand-populated
    with, now derived from the database instead."""
    with open(csv_path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    if len(rows) != 108:
        raise RuntimeError(
            f"{csv_path} has {len(rows)} rows, expected 108 -- refusing to seed from a "
            "watchlist file that doesn't match docs/CANDIDATE_UNIVERSE_V1.md's own count. "
            "This needs a human to look at why the file changed, not a silent partial seed."
        )

    result = []
    for row in rows:
        entity_id = seed_one(
            conn, row["sector"], row["watchlist_ticker"], row["sec_current_ticker"],
            row["sec_company_title"], row["cik"],
        )
        result.append((row["cik"], entity_id))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dsn", default=DB_DSN)
    args = parser.parse_args()

    conn = psycopg2.connect(args.dsn)
    try:
        seeded = seed_all(conn)
        conn.commit()
        log.info("Seeded/confirmed %d entities on the watchlist.", len(seeded))
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


if __name__ == "__main__":
    main()
